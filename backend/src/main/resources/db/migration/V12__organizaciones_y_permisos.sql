-- RF-03: Organizaciones y permisos

CREATE TABLE organizaciones (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    nombre VARCHAR(255) NOT NULL,
    activa BOOLEAN NOT NULL DEFAULT TRUE,
    creada_en TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE organizacion_miembros (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organizacion_id UUID NOT NULL REFERENCES organizaciones(id),
    usuario_id BIGINT NOT NULL REFERENCES usuarios(id),
    puede_administrar BOOLEAN NOT NULL DEFAULT FALSE,
    activo BOOLEAN NOT NULL DEFAULT TRUE,
    creado_en TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT uq_organizacion_miembro
        UNIQUE (organizacion_id, usuario_id)
);

CREATE INDEX ix_organizacion_miembros_usuario
    ON organizacion_miembros(usuario_id);

CREATE INDEX ix_organizacion_miembros_organizacion
    ON organizacion_miembros(organizacion_id);
